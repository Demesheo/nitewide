const test = require('node:test');
const assert = require('node:assert/strict');
const request = require('supertest');
const { randomUUID,randomBytes } = require('node:crypto');
const { assertManagedTestDatabase } = require('../scripts/test-database.cjs');
const { createFixture } = require('./admissions-fixture.cjs');
test('support conversations isolate requesters, guest recovery, admin permissions and durable retries',{ timeout: 90000 },async t => {
  assertManagedTestDatabase();
  const config = require('../src/config').getConfig();
  const db = require('../src/db/sequelize').createSequelize(config);
  const m = require('../src/db/models').initModels(db);
  try {
    const { ids } = await createFixture(m,config);
    const app = require('../src/app').createApp({ sequelize: db,models: m,config,services: { email: { enabled: false } } });
    const api = (method,path,userId = ids.guest) => request(app)[method](`/api${path}`).set('x-user-id',userId);
    const staff = await m.User.create({ email: `${randomUUID()}@support.test`,displayName: 'Support',isInternalAdmin: true,internalAdminRole: 'support' });
    const reader = await m.User.create({ email: `${randomUUID()}@support.test`,displayName: 'Read only',isInternalAdmin: true,internalAdminRole: 'read_only' });
    const input = { source: 'customer',title: 'Help with my booking',body: 'The entrance was difficult to find',category: 'admission',orderId: ids.order,idempotencyKey: randomUUID() };
    let thread;
    await t.test('customer intake atomically creates linked case and privately scopes booking context',async () => {
      const results = await Promise.all([api('post','/support/requests').send(input),api('post','/support/requests').send(input)]);
      assert.deepEqual(results.map(r => r.status),[200,200]);
      thread = results[0].body.data.thread;
      assert.equal(results[1].body.data.thread.id,thread.id);
      assert.equal(thread.orderId,ids.order);
      const [storedCase] = await db.query('SELECT c.priority FROM support_cases c JOIN support_conversations t ON t.case_id=c.id WHERE t.id=:id',{ replacements: { id: thread.id },type: require('sequelize').QueryTypes.SELECT });
      assert.equal(storedCase.priority,'high');
      assert.equal(results[0].body.data.messages.total,1);
      assert.equal('caseId' in thread,false);
      assert.equal('resolution' in thread,false);
      await api('get',`/support/messages/${thread.id}`,ids.owner).expect(404);
      await api('post','/support/requests',ids.outsider).send({ ...input,idempotencyKey: randomUUID() }).expect(404);
      await api('post','/support/requests',ids.outsider).send({ ...input,source: 'business',orderId: undefined,idempotencyKey: randomUUID() }).expect(403);
      await api('post','/support/requests').send({ ...input,body: 'Different retry' }).expect(409);
      const inbox = await api('get','/support/messages').query({ pageSize: 1 }).expect(200);
      assert.equal(inbox.body.data.total,1);
      await api('get','/support/messages').query({ pageSize: 51 }).expect(422);
    });
    await t.test('admin read versus reply permission, unread watermark and case state are authoritative',async () => {
      const detail = (await api('get',`/admin/support/messages/${thread.id}`,reader.id).expect(200)).body.data;
      assert.equal(detail.canReply,false);
      assert.notEqual(detail.messages.items[0].senderName,'You');
      await api('post',`/admin/support/messages/${thread.id}/replies`,reader.id).send({ body: 'Denied',idempotencyKey: randomUUID() }).expect(403);
      const reply = { body: 'We can help with the entrance.',idempotencyKey: randomUUID() };
      const replies = await Promise.all([api('post',`/admin/support/messages/${thread.id}/replies`,staff.id).send(reply),api('post',`/admin/support/messages/${thread.id}/replies`,staff.id).send(reply)]);
      assert.deepEqual(replies.map(r => r.status),[200,200]);
      let own = (await api('get',`/support/messages/${thread.id}`).expect(200)).body.data;
      assert.equal(own.messages.total,2);
      assert.equal(own.thread.unread,true);
      const oldMessageId = own.messages.items[0].id;
      await api('post',`/support/messages/${thread.id}/read`).send({ messageId: oldMessageId }).expect(200);
      assert.equal((await api('get',`/support/messages/${thread.id}`)).body.data.thread.unread,true);
      const acknowledgments = await Promise.all([api('post',`/support/messages/${thread.id}/read`).send({ messageId: own.messages.items.at(-1).id }),api('post',`/support/messages/${thread.id}/read`).send({ messageId: oldMessageId })]);
      assert.deepEqual(acknowledgments.map(r => r.status),[200,200]);
      assert.equal((await api('get',`/support/messages/${thread.id}`)).body.data.thread.unread,false);
      await api('post',`/support/messages/${thread.id}/read`).send({ messageId: oldMessageId }).expect(200);
      assert.equal((await api('get',`/support/messages/${thread.id}`)).body.data.thread.unread,false);
      const adminThread = (await api('get',`/admin/support/messages/${thread.id}`,staff.id)).body.data.thread;
      const caseDetail = (await api('get',`/admin/support/cases/${adminThread.caseId}`,staff.id)).body.data;
      assert.equal(caseDetail.supportThreadId,thread.id);
      await api('patch',`/admin/support/cases/${adminThread.caseId}`,staff.id).send({ version: caseDetail.case.version,status: 'resolved',resolution: 'INTERNAL SECRET',reason: 'PRIVATE AUDIT REASON' }).expect(200);
      own = (await api('get',`/support/messages/${thread.id}`).expect(200)).body.data;
      assert.equal(own.thread.status,'resolved');assert.equal(own.canReply,false);
      assert.equal(JSON.stringify(own).includes('INTERNAL SECRET'),false);
      await api('post',`/support/messages/${thread.id}/replies`).send({ body: 'More help',idempotencyKey: randomUUID() }).expect(409);
      await api('post',`/admin/support/messages/${thread.id}/replies`,staff.id).send(reply).expect(200);
      const filtered = await api('get','/admin/support/messages',staff.id).query({ status: 'open,in_progress',search: 'Help' }).expect(200);
      assert.equal(filtered.body.data.total,0);
      assert.equal(await m.Notification.count({ where: { userId: ids.guest,kind: 'support_message' } }),1);
      assert.equal(await m.Notification.count({ where: { userId: ids.guest,kind: 'support_status' } }),1);
      const privateOrder = await m.Order.create({ eventId: ids.otherEvent,buyerUserId: ids.outsider,status: 'paid',subtotalCents: 1000,totalCents: 1000,platformFeeCents: 0,idempotencyKey: randomUUID() });
      const updatedCase = (await api('get',`/admin/support/cases/${adminThread.caseId}`,staff.id)).body.data.case;
      await api('patch',`/admin/support/cases/${adminThread.caseId}`,staff.id).send({ version: updatedCase.version,orderId: privateOrder.id,eventId: ids.otherEvent,customerUserId: ids.outsider,title: 'PRIVATE INTERNAL CASE TITLE',reason: 'Private linked incident' }).expect(200);
      const stable = (await api('get',`/support/messages/${thread.id}`).expect(200)).body.data.thread;
      assert.equal(stable.orderId,ids.order);assert.equal(stable.eventId,ids.event);assert.equal(stable.title,input.title);
      assert.equal(JSON.stringify(stable).includes(privateOrder.id),false);
    });
    await t.test('current business membership scopes report context and keeps employee cases private',async () => {
      const employeeInput = { source: 'business',title: 'Employee reporting issue',body: 'My guestlist is not available',category: 'guestlist',organizationId: ids.org,eventId: ids.event,idempotencyKey: randomUUID() };
      const created = (await api('post','/support/requests',ids.employee).send(employeeInput).expect(200)).body.data.thread;
      await api('post','/support/requests',ids.employee).send({ ...employeeInput,orderId: ids.order,idempotencyKey: randomUUID() }).expect(404);
      await api('post','/support/requests',ids.owner).send({ ...employeeInput,orderId: ids.order,idempotencyKey: randomUUID() }).expect(200);
      await api('get',`/support/messages/${created.id}`,ids.owner).expect(404);
      await api('post','/support/requests',ids.promoter).send({ ...employeeInput,organizationId: undefined,idempotencyKey: randomUUID() }).expect(200);
      await api('post','/support/requests',ids.promoter).send({ ...employeeInput,eventId: ids.otherEvent,idempotencyKey: randomUUID() }).expect(404);
      await m.OrganizationEmployee.update({ status: 'removed' },{ where: { organizationId: ids.org,userId: ids.employee } });
      await api('post','/support/requests',ids.employee).send({ ...employeeInput,idempotencyKey: randomUUID() }).expect(403);
      await m.User.update({ lifecycleState: 'suspended' },{ where: { id: ids.employee } });
      await api('get',`/support/messages/${created.id}`,ids.employee).expect(403);
    });
    await t.test('public event references respect parent lifecycle while owned booking issues remain reportable',async () => {
      const body = { source: 'customer',title: 'Event support request',body: 'I need help locating this event',category: 'other',eventId: ids.event,idempotencyKey: randomUUID() };
      await api('post','/support/requests').send(body).expect(200);
      await m.Organization.update({ lifecycleState: 'suspended',status: 'suspended' },{ where: { id: ids.org } });
      await api('post','/support/requests').send({ ...body,idempotencyKey: randomUUID() }).expect(404);
      await api('post','/support/requests').send({ ...body,orderId: ids.order,idempotencyKey: randomUUID() }).expect(200);
      await m.Organization.update({ lifecycleState: 'active',status: 'active' },{ where: { id: ids.org } });
      await m.Location.update({ lifecycleState: 'suspended' },{ where: { id: ids.location } });
      await api('post','/support/requests').send({ ...body,idempotencyKey: randomUUID() }).expect(404);
      await m.Location.update({ lifecycleState: 'active' },{ where: { id: ids.location } });
    });
    await t.test('guest identity stays unverified and cannot acquire user identity through matching email',async () => {
      const countBefore = await m.User.count();
      const user = await m.User.findByPk(ids.guest);
      const recoveryToken = randomBytes(32).toString('hex');
      const body = { name: 'Claimed name',email: user.email,body: 'I cannot sign in',website: '',recoveryToken,idempotencyKey: randomUUID() };
      const results = await Promise.all([request(app).post('/api/support/access-requests').send(body),request(app).post('/api/support/access-requests').send(body)]);
      assert.deepEqual(results.map(r => r.status),[200,200]);
      const guest = results[0].body.data;
      assert.deepEqual(results[1].body.data,guest);
      const retry = (await request(app).post('/api/support/access-requests').send(body).expect(200)).body.data;
      assert.deepEqual(retry,guest);
      await request(app).post('/api/support/access-requests').send({ ...body,body: 'Edited uncertain retry',idempotencyKey: randomUUID() }).expect(409);
      const path = `/support/access-requests/${guest.id}`;
      await request(app).get(`/api${path}`).expect(404);
      await request(app).get(`/api${path}`).set('X-Support-Recovery-Token',randomBytes(32).toString('hex')).expect(404);
      await api('get',`/support/messages/${guest.id}`).expect(404);
      const detail = await request(app).get(`/api${path}`).set('X-Support-Recovery-Token',recoveryToken).expect(200);
      assert.equal(detail.body.data.thread.source,'account_access');
      const admin = (await api('get',`/admin/support/messages/${guest.id}`,staff.id).expect(200)).body.data;
      assert.equal(admin.thread.contactVerified,false);
      assert.equal(admin.thread.contactEmail,user.email);
      await request(app).post(`/api${path}/replies`).set('X-Support-Recovery-Token',recoveryToken).send({ body: 'Still need access',idempotencyKey: randomUUID() }).expect(200);
      const [stored] = await db.query('SELECT requester_user_id,recovery_token_hash FROM support_conversations WHERE id=:id',{ replacements: { id: guest.id },type: require('sequelize').QueryTypes.SELECT });
      assert.equal(stored.requester_user_id,null);assert.notEqual(stored.recovery_token_hash,recoveryToken);
      await request(app).post('/api/support/access-requests').send({ ...body,website: 'spam' }).expect(422);
      await request(app).post('/api/support/access-requests').send({ ...body,category: 'paid_booking' }).expect(422);
      assert.equal(await m.User.count(),countBefore);
      assert.equal(await m.OrganizerThread.count(),0);
      const service = require('../src/services/support-message-service').createSupportMessageService({ models: m,permissions: require('../src/services/permission-service').createPermissionService(m) });
      assert.deepEqual(await service.intake(null,body,'changed-client-ip'),guest);
      for (let i=0;i<4;i++) await request(app).post('/api/support/access-requests').send({ ...body,recoveryToken: randomBytes(32).toString('hex'),idempotencyKey: randomUUID() }).expect(200);
      await request(app).post('/api/support/access-requests').send({ ...body,recoveryToken: randomBytes(32).toString('hex'),idempotencyKey: randomUUID() }).expect(429);
      await db.query("UPDATE support_conversations SET created_at=NOW()-INTERVAL '91 days' WHERE id=:id",{ replacements: { id: guest.id } });
      await request(app).get(`/api${path}`).set('X-Support-Recovery-Token',recoveryToken).expect(404);
    });
  } finally { await db.close(); }
});
